"""Boot autostart switch for the Adam stack.

Single source of truth is systemd itself (unit enablement) plus the Docker
restart policy of the ASR container — nothing is duplicated into Config.json.
Config.json (system.autostart) only lists WHICH units/containers form the
"Adam starts on boot" set.

Algorithm:
  status  -> `systemctl is-enabled` for every unit + docker restart policy
             for every container; overall state = on | off | partial.
  enable  -> `sudo -n systemctl enable <unit>` for every unit,
             `docker update --restart=<policy> <container>` for containers.
  disable -> `sudo -n systemctl disable <unit>`, `docker update --restart=no`.
Switching never starts or stops anything right now — it only changes what
happens on the next boot. Each step is independent: one failure does not
abort the rest, and the caller gets a per-item report plus the fresh status.

Shared by the orchestrator API (/api/system/autostart) and the TUI
(scripts/adam_autostart.py). Must stay import-light (stdlib only).
"""
from __future__ import annotations

import re
import shutil
import subprocess
from typing import Any

# Only adam-* units may be toggled — guards against a Config.json typo turning
# the switch into "disable arbitrary system service".
UNIT_RE = re.compile(r"^adam-[a-z0-9-]+\.(service|target|timer)$")
CONTAINER_RE = re.compile(r"^adam-[a-z0-9-]+$")

DEFAULTS: dict[str, Any] = {
    "units": [
        "adam-llm.service",
        "adam-tts-silero.service",
        "adam-orchestrator.service",
        "adam-exhibition.target",
    ],
    "docker_containers": ["adam-asr-whisperx"],
    "docker_restart_policy": "unless-stopped",
    "command_timeout_sec": 15,
}

# systemctl is-enabled values that mean "will start on boot"
_ENABLED_STATES = {"enabled", "enabled-runtime", "alias"}


def resolve_cfg(section: dict[str, Any] | None) -> dict[str, Any]:
    """Merge system.autostart from Config.json over DEFAULTS and validate names."""
    cfg = {**DEFAULTS, **(section or {})}
    cfg["units"] = [u for u in cfg.get("units", []) if UNIT_RE.match(str(u))]
    cfg["docker_containers"] = [
        c for c in cfg.get("docker_containers", []) if CONTAINER_RE.match(str(c))
    ]
    return cfg


def _run(cmd: list[str], timeout: float) -> tuple[bool, str]:
    try:
        proc = subprocess.run(
            cmd,
            check=False,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            timeout=timeout,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return False, str(exc)
    return proc.returncode == 0, proc.stdout.strip()


def _unit_state(unit: str, timeout: float) -> str:
    # is-enabled exits non-zero for disabled/masked — the text is what matters
    _, out = _run(["systemctl", "is-enabled", unit], timeout)
    return (out.splitlines() or ["unknown"])[0].strip() or "unknown"


def _container_policy(name: str, timeout: float) -> str | None:
    """Docker restart policy name, or None if docker/container is missing."""
    docker = shutil.which("docker")
    if docker is None:
        return None
    ok, out = _run(
        [docker, "inspect", "-f", "{{.HostConfig.RestartPolicy.Name}}", name], timeout
    )
    return out.strip() if ok else None


def can_manage(cfg: dict[str, Any]) -> bool:
    """True if NOPASSWD sudoers rules cover enable+disable for every unit.

    `sudo -n -l <cmd>` is not enough: it succeeds for a password-protected
    (ALL) ALL rule too. So parse the listing and look for the exact commands
    on NOPASSWD lines (rules are generated by adam_install_systemd.sh).
    """
    ok, out = _run(["sudo", "-n", "-l"], float(cfg["command_timeout_sec"]))
    if not ok:
        return False
    nopasswd = " ".join(line for line in out.splitlines() if "NOPASSWD:" in line)
    return all(
        f"systemctl {verb} {unit}" in nopasswd
        for unit in cfg["units"]
        for verb in ("enable", "disable")
    )


def status(cfg: dict[str, Any]) -> dict[str, Any]:
    timeout = float(cfg["command_timeout_sec"])
    want_policy = str(cfg["docker_restart_policy"])
    items: list[dict[str, Any]] = []

    for unit in cfg["units"]:
        state = _unit_state(unit, timeout)
        items.append({
            "kind": "systemd",
            "name": unit,
            "state": state,
            "enabled": state in _ENABLED_STATES,
        })

    for name in cfg["docker_containers"]:
        policy = _container_policy(name, timeout)
        items.append({
            "kind": "docker",
            "name": name,
            "state": policy if policy is not None else "missing",
            "enabled": policy == want_policy,
            # A missing container can't be toggled; it doesn't count toward the verdict
            "present": policy is not None,
        })

    counted = [i for i in items if i.get("present", True)]
    on = sum(1 for i in counted if i["enabled"])
    if counted and on == len(counted):
        overall = "on"
    elif on == 0:
        overall = "off"
    else:
        overall = "partial"

    return {"state": overall, "enabled": overall == "on", "items": items}


def set_enabled(cfg: dict[str, Any], enabled: bool) -> dict[str, Any]:
    """Enable or disable boot autostart. Returns {ok, results, status}."""
    timeout = float(cfg["command_timeout_sec"])
    verb = "enable" if enabled else "disable"
    results: list[dict[str, Any]] = []

    for unit in cfg["units"]:
        ok, out = _run(["sudo", "-n", "systemctl", verb, unit], timeout)
        if not ok and "password is required" in out:
            out = "нет прав sudo: запустите scripts/adam_install_systemd.sh"
        results.append({"name": unit, "ok": ok, "detail": out or f"{verb} {unit}"})

    docker = shutil.which("docker")
    policy = str(cfg["docker_restart_policy"]) if enabled else "no"
    for name in cfg["docker_containers"]:
        if docker is None or _container_policy(name, timeout) is None:
            results.append({"name": name, "ok": True, "detail": "контейнер не найден — пропущен"})
            continue
        ok, out = _run([docker, "update", f"--restart={policy}", name], timeout)
        results.append({"name": name, "ok": ok, "detail": out or f"restart={policy}"})

    return {
        "ok": all(r["ok"] for r in results),
        "results": results,
        "status": status(cfg),
    }
