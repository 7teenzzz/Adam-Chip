print(f"Body starts at paragraph index {body_start_idx}")

# ── Phase 3: delete all paragraphs from body_start onwards ────────────────
# We'll remove them from the XML body element

body_xml = doc.element.body

# Collect all paragraph XML elements
all_para_els = body_xml.findall(qn("w:p"))
# Also collect table elements (images etc.)
all_children = list(body_xml)

# Find the XML element of the first body paragraph
first_body_el = paras[body_start_idx]._element

# Remove everything from first_body_el to the last sectPr
removing = False
to_remove = []
for child in all_children:
    if child is first_body_el:
        removing = True
    if removing:
        # Keep the final sectPr (section properties - page setup)
        if child.tag == qn("w:sectPr"):
            break
        to_remove.append(child)

for el in to_remove:
    body_xml.remove(el)

# ── Phase 4: append new body content ──────────────────────────────────────
# We insert before the sectPr

sect_pr = body_xml.find(qn("w:sectPr"))

def insert_para(text, style="Normal"):
    p = OxmlElement("w:p")
    r = OxmlElement("w:r")
    t = OxmlElement("w:t")
    t.text = text
    if text.startswith(" ") or text.endswith(" "):
        t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    r.append(t)
    p.append(r)
    # Apply style
    pPr = OxmlElement("w:pPr")
    pStyle = OxmlElement("w:pStyle")
    pStyle.set(qn("w:val"), style)
    pPr.append(pStyle)
    p.insert(0, pPr)
    body_xml.insert(list(body_xml).index(sect_pr), p)
    return p

def ins(text, style="Normal"):
    insert_para(text, style)

