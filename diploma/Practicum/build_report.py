# ── helpers ────────────────────────────────────────────────────────────────

def para_text(p):
    return "".join(r.text for r in p.runs)

def set_run_text(run, text):
    run.text = text

def replace_in_para(para, old, new):
    """Replace old→new across all runs of a paragraph."""
    full = para_text(para)
    if old not in full:
        return False
    # Try single-run replacement first
    for run in para.runs:
        if old in run.text:
            run.text = run.text.replace(old, new)
            return True
    # Multi-run: merge into first run, clear the rest
    new_full = full.replace(old, new)
    if para.runs:
        para.runs[0].text = new_full
        for r in para.runs[1:]:
            r.text = ""
    return True

def clear_para_text(para):
    for run in para.runs:
        run.text = ""

def set_para_text(para, text):
    """Overwrite paragraph text while preserving first-run formatting."""
    if para.runs:
        para.runs[0].text = text
        for r in para.runs[1:]:
            r.text = ""
    else:
        para.add_run(text)

def add_para(doc, text, style="Normal"):
    p = doc.add_paragraph(style=style)
    p.add_run(text)
    return p

def add_heading(doc, text, level):
    """Add heading paragraph."""
    style_map = {1: "Heading 1", 2: "Heading 2", 3: "Heading 3"}
    return add_para(doc, text, style=style_map[level])

def add_list_item(doc, text):
    return add_para(doc, text, style="List Paragraph")


